// Native WebView regression on an isolated, fictional workspace. Never use production data.
(async()=>{
 const invoke=(cmd,args={})=>window.__TAURI_INTERNALS__.invoke(cmd,args);
 const sleep=ms=>new Promise(r=>setTimeout(r,ms));
 const until=async(fn)=>{for(let i=0;i<100;i++){if(await fn())return;await sleep(100);}throw Error('Timed out');};
 const check=(v,m)=>{if(!v)throw Error(m);}; const checks=[];
 try {
  await until(()=>document.querySelector('.meeting-link'));
  const m=(await invoke('list_meetings'))[0];
  document.querySelector(`[data-meeting="${m.id}"]`).click();await sleep(900);
  check(!document.querySelector('footer'),'Footer still present');
  check(document.querySelector('.editor-toolbar').getBoundingClientRect().height<60,'Formatting toolbar wraps');
  check(!document.querySelector('.document-label'),'Redundant Markdown label');
  check(!document.querySelector('.minutes-section h3, .document-sources'),'Minutes still use per-utterance cards');
  const citation=document.querySelector('[data-citation]');check(citation,'No inline citation');citation.click();await sleep(500);
  check(document.querySelector('#modal .citation-sources'),'Source quotes missing');
  check(getComputedStyle(document.querySelector('#modal')).opacity==='1','Dialog invisible after animation');
  document.querySelector('[data-action="close-modal"]').click();
  checks.push('Continuous document, superscript sources, one-row editor, no footer');
  const before=await invoke('snapshot',{id:m.id});const note=before.notes.find(n=>n.kind==='document');
  document.querySelector('[data-action="delete-note"]').click();await until(()=>document.querySelector('.confirm-dialog'));await sleep(400);
  const d=document.querySelector('.confirm-dialog');check(d.open && getComputedStyle(d).opacity==='1','Confirmation not visible');
  const rect=d.getBoundingClientRect();check(rect.top>=0&&rect.bottom<=innerHeight,'Confirmation outside viewport');
  check(getComputedStyle(d,'::backdrop').backgroundColor!=='rgb(255, 255, 255)','Opaque modal backdrop');
  d.querySelector('[value="cancel"]').click();await sleep(200);
  check((await invoke('snapshot',{id:m.id})).notes.some(n=>n.id===note.id),'Cancel removed note');
  document.querySelector('[data-action="delete-note"]').click();await until(()=>document.querySelector('.confirm-dialog'));
  document.querySelector('.confirm-dialog [value="delete"]').click();await sleep(1000);
  check(!(await invoke('snapshot',{id:m.id})).notes.some(n=>n.id===note.id),'Deleted note still in meeting');
  const deleted=(await invoke('list_library')).find(n=>n.id===note.id);check(deleted.deleted&&deleted.content===note.content,'Note not recoverable');
  await invoke('save_library_entry',{entry:{...deleted,deleted:false}});
  check((await invoke('snapshot',{id:m.id})).notes.some(n=>n.id===note.id&&n.content===note.content),'Restore lost note');
  checks.push('Note delete requires confirmation; cancel preserves it; restore retains original');
  const speaker=await invoke('rename_speaker',{meeting:m.id,id:null,name:'Example speaker'});
  document.querySelector('[data-action="speakers"]').click();await until(()=>document.querySelector('[data-speaker-delete]'));
  document.querySelector(`[data-speaker-delete="${speaker}"]`).click();await until(()=>document.querySelector('.confirm-dialog'));
  document.querySelector('.confirm-dialog [value="delete"]').click();await sleep(600);
  check(!(await invoke('snapshot',{id:m.id})).meeting.speaker_names[speaker],'Speaker not removed');
  document.querySelector('[data-speaker-action="close"]').click();
  checks.push('Speaker removal has a second confirmation');
  document.dispatchEvent(new CustomEvent('open-settings',{detail:'shortcuts'}));await until(()=>document.querySelector('.shortcuts'));
  check(document.querySelector('.shortcuts').textContent.includes(/Mac/.test(navigator.platform)?'⌘':'Ctrl'),'Wrong platform shortcuts');
  document.querySelector('[data-section="storage"]').click();await until(()=>document.querySelector('.storage-legend'));
  const storage=await invoke('storage_usage');check(storage.bundled_models>1000000,'Bundled model storage missing');
  check(document.querySelectorAll('.storage-legend>span').length===6,'Storage categories incomplete');
  document.querySelector('[data-section="transcription"]').click();await until(()=>document.querySelector('[data-pref="translation_mode"]'));
  check(document.querySelector('[data-pref="translation_mode"]').options.length===4,'Four translation modes missing');
  check(document.querySelector('[data-pref="minutes_language"]').options.length===3,'Minutes language control missing');
  checks.push('Storage counts bundled weights; shortcuts and separate language settings work');
  document.querySelector('[data-settings="back"]').click();await sleep(900);
  document.querySelector(`[data-action="delete-meeting"][data-id="${m.id}"]`).click();await until(()=>document.querySelector('.confirm-dialog'));
  document.querySelector('.confirm-dialog [value="cancel"]').click();await sleep(200);
  check((await invoke('list_meetings')).some(v=>v.id===m.id),'Cancel deleted meeting');
  document.querySelector(`[data-action="delete-meeting"][data-id="${m.id}"]`).click();await until(()=>document.querySelector('.confirm-dialog'));
  document.querySelector('.confirm-dialog [value="delete"]').click();await sleep(700);
  check(!(await invoke('list_meetings')).some(v=>v.id===m.id),'Meeting not in trash');
  document.dispatchEvent(new CustomEvent('open-settings',{detail:'storage'}));await until(()=>document.querySelector('[data-settings="restore-meeting"]'));
  document.querySelector(`[data-settings="restore-meeting"][data-id="${m.id}"]`).click();await sleep(700);
  check((await invoke('list_meetings')).some(v=>v.id===m.id),'Meeting restore failed');
  checks.push('Meeting deletion is confirmed and recoverable from Storage');
  document.querySelector('[data-settings="back"]').click();await sleep(1500);
  document.querySelector(`[data-meeting="${m.id}"]`)?.click();await sleep(600);
  check(document.querySelectorAll('.meeting-header').length===1,'Duplicated meeting header after reopening');
  await invoke('ui_test_resize',{width:740,height:560});await sleep(700);
  for(const selector of ['.transcript-toggle','.caption-toggle','#record']) {const e=document.querySelector(selector),r=e.getBoundingClientRect();check(r.left>=0&&r.right<=innerWidth&&r.top>=0&&r.bottom<=innerHeight,'Control outside narrow viewport: '+selector);check(e.contains(document.elementFromPoint(r.x+r.width/2,r.y+r.height/2)),'Obscured control: '+selector);}
  check(document.documentElement.scrollWidth<=innerWidth,'Outer horizontal overflow');
  checks.push('Live controls remain visible and clickable at 740 × 560');
  await invoke('ui_test_resize',{width:1160,height:780});await sleep(600);
  await invoke('ui_test_report',{report:{passed:true,checks,viewport:{width:innerWidth,height:innerHeight}}});
 } catch(e){await invoke('ui_test_report',{report:{passed:false,error:String(e),checks}});}
})();
